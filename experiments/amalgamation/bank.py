"""§34.3z²⁸⁴: the counterexample bank (adjoint-math-research v1.0). Never delete a file from bank/.
bank/index.json lists every banked model: file, the statement it refutes, the section, the world it lives in.
Every quantity below is computed from the definitions (rstages.stages, a_of); no SAT encoding is involved.

  python3 bank.py coords                  write bank/INDEX.md: room coordinates of every banked model
  python3 bank.py replay NAME [NAME ...]  evaluate built-in statements on every banked model of the world W0 + n1
  python3 bank.py replay --file P.py      the same for `def holds(m) -> bool` (and optional `def hyp(m) -> bool`) in P.py

Room coordinates: |L|, height H, width (largest antichain), N (index of d, the last nonzero element of the bot-descent),
branch (a: h(d) = 2; b: d a bad atom; g: d a good atom), the bot-orbit of mu (length until it repeats, and whether it
reaches a fixed point), |M2| (height-2 elements of Z).
Model API (class M): L, F, n, le, h, bot, top, Z, M2, atoms, d, N, branch, desc(x), lam(x), lidx(x), exits(x), c(x),
mu(x), good(y), fixed(q), w0 (W0 + n1 holds)."""
import sys, os, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, '..', 'separation'))
import tight_probe as tp
from rstages import stages, a_of
ss = tp.ss
BANK = os.path.join(HERE, 'bank')

class M:
    def __init__(s, sets, F):
        s.L = L = ss.Lat(sets); s.F = F; s.n = n = L.n; s.le = le = L.le; s.h = h = L.rank; s.bot = bot = L.bot; s.top = L.top
        st = stages(L, F); inR = lambda z, i: st[z] is not None and st[z] <= i
        s.Z = [x for x in range(n) if F[bot][x] == bot]
        s.w0 = (a_of(L, F, bot) == bot and all(h[z] <= 2 for z in range(n) if inR(z, 2)) and not inR(L.top, 2)
                and any(h[z] > 1 for z in range(n) if inR(z, 1)))
        s.M2 = [m for m in s.Z if h[m] == 2]; s.atoms = [q for q in s.Z if h[q] == 1]
        tb = s.desc(bot); s.tb = tb; nz = [t for t in tb if t != bot]
        s.d = nz[-1] if nz else None; s.N = tb.index(s.d) if s.d is not None else None
        s.branch = None if s.d is None else ('a' if h[s.d] == 2 else ('g' if s.good(s.d) else 'b'))
    def desc(s, x):
        v = s.top; out = []
        while v not in out: out.append(v); v = s.F[x][v]
        return out
    def lidx(s, x):
        d = s.desc(x); return next((i for i, v in enumerate(d) if s.h[v] <= 2), None)
    def lam(s, x):
        i = s.lidx(x); return None if i is None else s.desc(x)[i]
    def exits(s, x):
        p = s.lam(x); return p is not None and s.F[s.bot][p] != s.bot
    def c(s, x): return s.F[s.bot][s.lam(x)] if s.exits(x) else None
    def mu(s, x):
        p = s.lam(x)
        if p is None: return None
        return p if s.F[s.bot][p] == s.bot else s.F[s.bot][p]
    def good(s, y): return s.le[y][a_of(s.L, s.F, y)] or y in s.desc(y)
    def fixed(s, q): return s.mu(q) == q

def width(L):
    n = L.n; lt = [[L.le[i][j] and i != j for j in range(n)] for i in range(n)]; match = [-1] * n
    def aug(u, seen):
        for v in range(n):
            if lt[u][v] and not seen[v]:
                seen[v] = True
                if match[v] < 0 or aug(match[v], seen): match[v] = u; return True
        return False
    return n - sum(aug(u, [False] * n) for u in range(n))          # Dilworth: n - maximum matching of the strict order

def models(entry):
    M_ = json.load(open(os.path.join(BANK, entry['file'])))
    return M_ if isinstance(M_, list) else [M_]

def orbit(m):
    x = m.bot; seen = []
    while x is not None and x not in seen: seen.append(x); x = m.mu(x)
    fix = x is not None and m.mu(x) == x
    return len(seen), ('fixed' if fix else ('cycle' if x is not None else 'no landing'))

BUILTIN = {   # name: (hypothesis, statement); hypothesis 'offg' = d is not a good atom
  'GoodAtom1': (lambda m: True, lambda m: any(m.good(q) for q in m.atoms)),
  'Cert1': (lambda m: True, lambda m: any(x != m.bot and m.exits(x) and m.le[m.c(x)][x] for x in m.Z)),
  'CertAtom': (lambda m: True, lambda m: any(m.fixed(q) for q in m.atoms)),
  'TopCert': (lambda m: m.branch != 'g', lambda m: any(m.exits(x) and m.le[m.c(x)][x] for x in m.M2)),
  'FixBelow': (lambda m: m.branch != 'g', lambda m: any(m.fixed(q) and any(m.le[q][x] for x in m.M2) for q in m.atoms)),
  'NMGood': (lambda m: m.branch != 'g', lambda m: any(m.good(q) and any(m.le[q][x] for x in m.M2) for q in m.atoms)),
  'ExitM2': (lambda m: m.branch != 'g', lambda m: any(m.exits(x) for x in m.M2)),
  'BotOrbit': (lambda m: True, lambda m: orbit(m)[1] == 'fixed'),
}

def main():
    if sys.argv[1] == 'coords':
        idx = json.load(open(os.path.join(BANK, 'index.json'))); lines = ['# Counterexample bank (generated by bank.py coords; never delete a model)', '',
            '| file | refutes | § | world | \\|L\\| | H | width | N | branch | ⊥-orbit | \\|M2\\| |', '|---|---|---|---|---|---|---|---|---|---|---|']
        for e in idx:
            for k, (sets_F) in enumerate(models(e)):
                m = M(sets_F['sets'], sets_F['F']); ol, ok = orbit(m) if m.d is not None else (None, None)
                lines.append(f"| {e['file']}{'#' + str(k) if len(models(e)) > 1 else ''} | {e['statement']} | {e['section']} | {e['world']}{' (W0 check FAILED)' if e['world'].startswith('W0+') and not m.w0 else ''} | {m.n} | {m.L.height} | {width(m.L)} | {m.N} | {m.branch} | {ol} {ok} | {len(m.M2)} |")
        open(os.path.join(BANK, 'INDEX.md'), 'w').write('\n'.join(lines) + '\n'); print('\n'.join(lines))
    elif sys.argv[1] == 'replay':
        if sys.argv[2] == '--file':
            ns = {}; exec(open(sys.argv[3]).read(), ns); tests = {os.path.basename(sys.argv[3]): (ns.get('hyp', lambda m: True), ns['holds'])}
        else: tests = {k: BUILTIN[k] for k in sys.argv[2:]}
        idx = json.load(open(os.path.join(BANK, 'index.json')))
        for name, (hyp, st) in tests.items():
            print(f'bank replay {name} | over every banked model of W0 + n1 | FAIL = the statement is false on that model')
            tally = {'pass': 0, 'FAIL': 0, 'outside hypothesis': 0, 'not W0+n1': 0}
            for e in idx:
                for k, mf in enumerate(models(e)):
                    m = M(mf['sets'], mf['F'])
                    if not m.w0: tally['not W0+n1'] += 1; continue
                    if not hyp(m): tally['outside hypothesis'] += 1; continue
                    ok = st(m); tally['pass' if ok else 'FAIL'] += 1
                    if not ok: print(f"  FAIL on {e['file']}#{k} (|L| = {m.n}, H = {m.L.height}, branch {m.branch})")
            print(f'  {name}: {tally}')

if __name__ == '__main__': main()
