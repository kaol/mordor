"""Emit lean/Mordor/FinGenKL.lean: a kernel-checked refutation of the k×l labelling (log §34.3m).

Every clause of `labelling.py` is tagged with the `FinGen.lean` lemma that proves it for a cut counterexample `Cx`;
a CaDiCaL unsat core (selector literals, iterated to a fixpoint) is emitted as `have`s and `bv_decide` closes it.

  python3 fg_lean.py K L"""
import sys, itertools
from pysat.solvers import Cadical153
from labelling import subsets

def lit_set(S, n): return '(' + '{' + ', '.join(str(i) for i in sorted(S)) + '}' + f' : Finset (Fin {n}))'
def lst(S): return '[' + ', '.join(str(i) for i in sorted(S)) + ']'

def build(k, l):
    As, Bs = subsets(k), subsets(l); cells = [(A, B) for A in As for B in Bs]
    v = {}; nv = [0]
    def var(key):
        if key not in v: nv[0] += 1; v[key] = nv[0]
        return v[key]
    sA = lambda A: lit_set(A, k); sB = lambda B: lit_set(B, l)
    z = lambda A, B: f"(F (Finset.inf {sA(A)} p) (Finset.sup {sB(B)} u))"
    ne = lambda S, n: f"⟨{min(S)}, by decide⟩"
    cls = []
    for (A, B) in cells:
        c = (A, B); d = var(('D', c))
        a = [var(('a', c, i)) for i in range(k)]; b = [var(('b', c, j)) for j in range(l)]
        cls.append(([-d] + a, f"cl_genD H {z(A,B)} {lst(range(k))} (by decide)"))
        cls.append(([d] + b, f"cl_genU H {z(A,B)} {lst(range(l))} (by decide)"))
        cls.append(([-a[i] for i in sorted(A)], f"cl_nwD H (A := {sA(A)}) (B := {sB(B)}) {ne(A,k)} {ne(B,l)} {lst(A)} (by decide)"))
        cls.append(([-b[j] for j in sorted(B)], f"cl_nwU H (A := {sA(A)}) (B := {sB(B)}) {ne(A,k)} {ne(B,l)} {lst(B)} (by decide)"))
        for i in range(k): cls.append(([-a[i], d], f"cl_aD H {z(A,B)} {i}"))
        for j in range(l): cls.append(([-b[j], -d], f"cl_bU H {z(A,B)} {j}"))
    for (A, B) in cells:
        ups = [(A - {i}, B) for i in A if len(A) > 1] + [(A, B | {j}) for j in range(l) if j not in B]
        for (A2, B2) in ups:
            c, c2 = (A, B), (A2, B2)
            args = f"(A := {sA(A)}) (A' := {sA(A2)}) (B := {sB(B)}) (B' := {sB(B2)}) (by decide) (by decide)"
            for i in range(k): cls.append(([-var(('a', c2, i)), var(('a', c, i))], f"cl_amono H {args} {i}"))
            for j in range(l): cls.append(([-var(('b', c, j)), var(('b', c2, j))], f"cl_bmono H {args} {j}"))
    return cls, nv[0]

def core(cls, nv, minimize=True):
    S = Cadical153(); sel = []
    for n, (c, _) in enumerate(cls):
        s = nv + 1 + n; sel.append(s); S.add_clause(c + [-s])
    keep = sel
    while True:
        assert not S.solve(assumptions=keep)
        new = sorted(S.get_core())
        if len(new) == len(keep): break
        keep = new
    for s in (list(keep) if minimize else []):             # deletion pass: a minimal unsat subset
        trial = [t for t in keep if t != s]
        if not S.solve(assumptions=trial): keep = sorted(S.get_core()) if len(S.get_core()) < len(trial) else trial
    return [cls[s - nv - 1] for s in keep]

def emit(k, l, minimize=True):
    cls, nv = build(k, l); C = core(cls, nv, minimize)
    out = [f"""import Mordor.FinGen

/-! # The Cut Lemma for {k} × {l}-generated cuts (machine-generated by `experiments/fgcut/fg_lean.py`)

`lab{k}{l}` refutes a unsat core ({len(C)} of {len(cls)} clauses) of the {k} × {l} labelling; each clause is an
instance of a `FinGen.lean` lemma and `bv_decide` checks the propositional refutation. Do not edit by hand; regenerate. -/

namespace Mordor.FinGen
set_option maxHeartbeats 0
set_option maxRecDepth 100000

theorem lab{k}{l} {{α : Type*}} [Lattice α] [BoundedOrder α] {{F : α → α → α}} {{D : Set α}}
    {{p : Fin {k} → α}} {{u : Fin {l} → α}} (H : Cx F D p u) : False := by"""]
    for n, (_, t) in enumerate(C): out.append(f"  have c{n} := {t}")
    out.append("  simp only [List.any_cons, List.any_nil, Bool.or_false] at *")
    out.append("  bv_decide\n\nend Mordor.FinGen\n")
    return '\n'.join(out), len(C), len(cls)

if __name__ == '__main__':
    k, l = int(sys.argv[1]), int(sys.argv[2])
    src, nc, nt = emit(k, l, '--fast' not in sys.argv)
    open(f"/home/user/mordor/lean/Mordor/FinGen{k}{l}.lean", 'w').write(src)
    print(f"({k},{l}): core {nc}/{nt} clauses")
