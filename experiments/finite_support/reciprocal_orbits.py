"""Reciprocal support orbits (log §34.3z⁹⁹), z3.

Support atoms p_1, p_2 ∈ D with p_1 ∨ p_2 ∉ D, q_1, q_2 ∉ D with q_1 ∧ q_2 ∈ D (|P| = |Q| = 2: proper faces are the
atoms). Column orbits c^j (from ⊥ along column q_j, exit D first at step N_j) and row orbits y^i (from ⊤ along row
p_i, enter D first at step M_i), all named; F given on EVERY named (D-element, outside element) pair, monotone,
witness-free. D is either an abstract down-set on the named elements (`abstract`) or generated by two generators
g_1 = p_1, g_2 = p_2 (`gen2`). Reports SAT and, per pair (i, j), the escape type at the first support failures
(A-side: c^j_s ∈ D; B-side: y^i_t ∉ D); then forces all-A, all-B and alternating patterns; `nodich` (some pair with neither type) checks the encoding
against first_failure_dichotomy (expected UNSAT)."""
import itertools, sys
from z3 import *
def run(mode, N, M, force=None):
    c = {j: ['bot'] + [f"c{j}_{n}" for n in range(1, N[j] + 1)] for j in (1, 2)}
    y = {i: ['top'] + [f"y{i}_{m}" for m in range(1, M[i] + 1)] for i in (1, 2)}
    base = ['bot', 'top', 'p1', 'p2', 'q1', 'q2', 'p12', 'q12'] + (['g12'] if mode == 'gen2' else [])
    named = base + [x for j in (1, 2) for x in c[j][1:]] + [x for i in (1, 2) for x in y[i][1:]]
    rowsD = [x for j in (1, 2) for x in c[j][:-1]] + ['p1', 'p2', 'q12'] + [y[i][-1] for i in (1, 2)] + (['g12'] if mode == 'gen2' else [])
    colsO = ['top', 'q1', 'q2', 'p12'] + [c[j][-1] for j in (1, 2)] + [x for i in (1, 2) for x in y[i][:-1]]
    rowsD = list(dict.fromkeys(rowsD)); colsO = list(dict.fromkeys(colsO))
    cell = {(r, k): f"F[{r},{k}]" for r in rowsD for k in colsO}
    E = list(dict.fromkeys(named + list(cell.values())))
    s = Solver(); le = {(a, b): Bool(f"le|{a}|{b}") for a in E for b in E}
    for a in E:
        s.add(le[a, a], le['bot', a], le[a, 'top'])
        for b in E:
            for w in E: s.add(Implies(And(le[a, b], le[b, w]), le[a, w]))
    if mode == 'gen2':
        inD = {a: Or(le[a, 'p1'], le[a, 'p2']) for a in E}
        s.add(Not(le['p1', 'p2']), Not(le['p2', 'p1']))
        s.add(le['g12', 'p1'], le['g12', 'p2'], *[Implies(And(le[w, 'p1'], le[w, 'p2']), le[w, 'g12']) for w in E])
    else:
        inD = {a: Bool(f"D|{a}") for a in E}
        for a in E:
            for b in E: s.add(Implies(And(le[a, b], inD[b]), inD[a]))
    def lub(z, xs): s.add([le[q, z] for q in xs]); s.add([Implies(And([le[q, w] for q in xs]), le[z, w]) for w in E])
    def glb(z, xs): s.add([le[z, q] for q in xs]); s.add([Implies(And([le[w, q] for q in xs]), le[w, z]) for w in E])
    lub('p12', ['p1', 'p2']); glb('q12', ['q1', 'q2'])
    s.add(inD['bot'], Not(inD['top']))
    s.add([inD[r] for r in rowsD]); s.add([Not(inD[k]) for k in colsO])
    for (r, k), v in cell.items():
        for (r2, k2), v2 in cell.items():
            if (r, k) != (r2, k2): s.add(Implies(And(le[r, r2], le[k, k2]), le[v, v2]))
        s.add(Not(le[v, r]), Not(le[k, v]))
    eq = lambda a, b: And(le[a, b], le[b, a])
    for j in (1, 2):
        for n in range(N[j]): s.add(eq(c[j][n + 1], cell[(c[j][n], f"q{j}")]))
    for i in (1, 2):
        for m in range(M[i]): s.add(eq(y[i][m + 1], cell[(f"p{i}", y[i][m])]))
    # escape type per (i, j): A-side iff some c^j_n in D (n < N_j) is not below p_i
    Aside = {(i, j): Or([Not(le[c[j][n], f"p{i}"]) for n in range(1, N[j])] or [BoolVal(False)]) for i in (1, 2) for j in (1, 2)}
    Bside = {(i, j): Or([Not(le[f"q{j}", y[i][m]]) for m in range(1, M[i])] or [BoolVal(False)]) for i in (1, 2) for j in (1, 2)}
    if force == 'allA': s.add(*[Aside[ij] for ij in Aside], *[Not(Bside[ij]) for ij in Bside])
    if force == 'allB': s.add(*[Bside[ij] for ij in Bside], *[Not(Aside[ij]) for ij in Aside])
    if force == 'nodich': s.add(Or([And(Not(Aside[ij]), Not(Bside[ij])) for ij in Aside]))
    if force == 'alt': s.add(Aside[1, 1], Not(Bside[1, 1]), Bside[1, 2], Not(Aside[1, 2]), Bside[2, 1], Not(Aside[2, 1]), Aside[2, 2], Not(Bside[2, 2]))
    r = s.check()
    out = str(r)
    if r == sat and force is None:
        mo = s.model()
        out += " | escape types: " + ", ".join(f"({i},{j})={'A' if is_true(mo.eval(Aside[i,j])) else ''}{'B' if is_true(mo.eval(Bside[i,j])) else ''}" for i in (1, 2) for j in (1, 2))
    return out
for mode in ['abstract', 'gen2']:
    for N, M in [({1: 2, 2: 2}, {1: 2, 2: 2}), ({1: 2, 2: 3}, {1: 3, 2: 2})]:
        print(f"{mode} N={N} M={M}: {run(mode, N, M)}", flush=True)
        for force in ['nodich', 'allA', 'allB', 'alt']:
            print(f"   forced {force}: {run(mode, N, M, force)}", flush=True)
