"""Pivot spectra of good words under one-letter enlargement (log §34.3z¹⁰⁹, brief Part 4).

For fixed global selectors (f1, f2), the mod-2 pivot spectrum of (P, U) is the set of cells occurring as pivot cells
of an odd number of good words. Candidate transport identities under adding a letter x, tested on random selectors:
  T1  spec(P, U) and spec(P + x, U) agree on the cells not involving x;
  T2  the parity of good words whose pivot lies in a fixed down-set 𝒟 of cells (a D-filter: z monotone in the cell
      order, so the cells with z ∈ D form a down-set) is the same before and after.
Each is checked for every enlargement of random instances; a single failure discards the identity."""
import itertools, random
from good_words import good
def subsets(xs): return [frozenset(c) for r in range(1, len(xs) + 1) for c in itertools.combinations(xs, r)]
def pivots(P, U, f1, f2):
    sp = {}
    for w in itertools.permutations(P + U):
        if good(w, P, U, f1, f2):
            k = len(P); pre = w[:k]
            c = (frozenset(x for x in P if x not in pre), frozenset(x for x in U if x in pre))
            sp[c] = sp.get(c, 0) + 1
    return sp
def below(c, c2):  # z(c) <= z(c2) forced: A2 ⊆ A, B ⊆ B2
    return c2[0] <= c[0] and c[1] <= c2[1]
def run(nP, nU, trials, seed=3):
    rnd = random.Random(seed); P = tuple(f"p{i}" for i in range(nP)); U = tuple(f"u{j}" for j in range(nU))
    cells = [(A, B) for A in subsets(P) for B in subsets(U)]
    stats = dict(T1=0, T2=0, tot=0)
    for _ in range(trials):
        f1 = {c: rnd.choice(sorted(c[0])) for c in cells}; f2 = {c: rnd.choice(sorted(c[1])) for c in cells}
        # random down-set of cells (generated by random maximal cells)
        gens = rnd.sample(cells, rnd.randint(1, 4)); Dset = {c for c in cells if any(below(c, g) for g in gens)}
        big = pivots(P, U, f1, f2)
        for x in P + U:
            Ps = tuple(y for y in P if y != x); Us = tuple(y for y in U if y != x)
            if not Ps or not Us: continue
            small = pivots(Ps, Us, f1, f2); stats['tot'] += 1
            common = {c for c in set(big) | set(small) if x not in c[0] and x not in c[1]}
            if any(big.get(c, 0) % 2 != small.get(c, 0) % 2 for c in common): stats['T1'] += 1
            pb = sum(v for c, v in big.items() if c in Dset) % 2; ps = sum(v for c, v in small.items() if c in Dset) % 2
            if pb != ps: stats['T2'] += 1
    return stats
if __name__ == '__main__':
    for nP, nU, tr in [(2, 2, 300), (3, 2, 150), (2, 3, 150), (3, 3, 30)]:
        st = run(nP, nU, tr)
        print(f"|P|={nP} |U|={nU}: enlargements tested {st['tot']}; T1 fails {st['T1']}, T2 fails {st['T2']}", flush=True)
