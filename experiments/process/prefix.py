"""Finite prefixes of the capture process on the full subset grid (log §34.3z⁶⁵), SAT (CaDiCaL via pysat).

Elements (preorder on named elements): ⊥, ⊤; row generators p_1..p_k (maximal in D, pairwise incomparable); column
generators u_1..u_b introduced one per stage (minimal outside D, pairwise incomparable); meets m_A (A ⊆ rows,
nonempty) and joins v_B (B ⊆ introduced columns, nonempty) as glb/lub among named elements; values z_{A,B}.
Constraints: D a down-set with ⊥ ∈ D ∌ ⊤; F monotone on all named cells; no-witness at every cell; "D generated by
p_1..p_k" (every named D-element lies below some p_i) when `gen` is given.
Process: stage t (t = 1..b-1) selects a cell over p_1..p_k × u_1..u_t that is NOT captured by the current generators
(D-valued: below no p_i; else: above no u_j, j ≤ t) and, being outside D (forced when `gen`), u_{t+1} is a minimal
capturer of it (u_{t+1} ≤ value).
A real counterexample whose cut has k maximal elements gives a model for every b (restrict the true lattice to the
named elements). So UNSAT at some b would be a proof that the process stops, i.e. Cut for such cuts.
  python3 prefix.py k b_max [gen] [h=H]
With h=H the named elements must have edge-height ≤ H; UNSAT then means the process forces chains longer than H."""
import itertools, sys, time
from pysat.solvers import Cadical153
k = int(sys.argv[1]); bmax = int(sys.argv[2]); GEN = 'gen' in sys.argv
FLAT = 'flat' in sys.argv     # ask for a model in which some initial-segment join does not grow (t ≥ 1): v[0..t+1] ≤ v[0..t]
HB = next((int(a[2:]) for a in sys.argv if a.startswith('h=')), None)   # edge-height bound on the named elements

def run(b):
    S = Cadical153(); nv = [0]; var = {}
    def V(*key):
        if key not in var: nv[0] += 1; var[key] = nv[0]
        return var[key]
    rowsets = [frozenset(A) for r in range(1, k + 1) for A in itertools.combinations(range(k), r)]
    colsets = [frozenset(B) for r in range(1, b + 1) for B in itertools.combinations(range(b), r)]
    m = {A: (('p', min(A)) if len(A) == 1 else ('m', A)) for A in rowsets}
    v = {B: (('u', min(B)) if len(B) == 1 else ('v', B)) for B in colsets}
    z = {(A, B): ('z', A, B) for A in rowsets for B in colsets}
    E = ['bot', 'top'] + list(dict.fromkeys(list(m.values()) + list(v.values()))) + list(z.values())
    le = lambda x, y: V('le', x, y); D = lambda x: V('D', x); add = S.add_clause
    for x in E:
        add([le(x, x)]); add([le('bot', x)]); add([le(x, 'top')])
        for y in E:
            if x != y:
                add([-le(x, y), -D(y), D(x)])
                for w in E:
                    if w != x and w != y: add([-le(x, y), -le(y, w), le(x, w)])
    add([D('bot')]); add([-D('top')])
    P = [('p', i) for i in range(k)]; U = [('u', j) for j in range(b)]
    for p in P:
        add([D(p)])
        for x in E:
            if x != p: add([-le(p, x), le(x, p), -D(x)])                   # maximal in D
    for u in U:
        add([-D(u)])
        for x in E:
            if x != u: add([-le(x, u), le(u, x), D(x)])                    # minimal outside D
    for g, h in itertools.permutations(P, 2): add([-le(g, h)])
    for g, h in itertools.permutations(U, 2): add([-le(g, h)])
    for A in rowsets:
        if len(A) > 1:
            for i in A: add([le(m[A], ('p', i))])
            for w in E: add([-le(w, ('p', i)) for i in A] + [le(w, m[A])])
    for B in colsets:
        if len(B) > 1:
            for j in B: add([le(('u', j), v[B])])
            for w in E: add([-le(('u', j), w) for j in B] + [le(v[B], w)])
    if GEN:
        for x in E:
            add([-D(x)] + [le(x, p) for p in P])
    if HB is not None:                                                      # rank(x) >= l literals, strict < raises rank
        g = lambda x, l: V('g', x, l)
        for x in E:
            add([-g(x, HB + 1)])
            for y in E:
                if x != y:
                    add([-le(x, y), le(y, x), g(y, 1)])
                    for l in range(1, HB + 1): add([-le(x, y), le(y, x), -g(x, l), g(y, l + 1)])
    cells = list(z.items())
    for (A, B), zz in cells:
        add([-le(zz, m[A])]); add([-le(v[B], zz)])                        # no witness
        for (A2, B2), zz2 in cells:
            if (A, B) != (A2, B2): add([-le(m[A], m[A2]), -le(v[B], v[B2]), le(zz, zz2)])
    for t in range(1, b):                                                   # stage t introduces u_t (0-based)
        cand = [(A, B) for A in rowsets for B in colsets if max(B) < t]
        sel = [V('sel', t, c) for c in cand]; add(sel)
        for c, s_ in zip(cand, sel):
            zz = z[c]
            add([-s_, -D(zz)])                                              # pivot outside D (capturer is a column)
            for j in range(t): add([-s_, -le(('u', j), zz)])                # not captured by u_0..u_{t-1}
            add([-s_, le(('u', t), zz)])                                    # u_t captures it
    if FLAT:
        if b < 3: return None, len(E), nv[0], 0.0
        segs = [v[frozenset(range(t + 1))] for t in range(b)]
        flat = [V('flat', t) for t in range(1, b - 1)]; add(flat)      # t = 0 would be u_1 ≤ u_0 (antichain)
        for t, f in zip(range(1, b - 1), flat): add([-f, le(segs[t + 1], segs[t])])
    t0 = time.time(); r = S.solve()
    return r, len(E), nv[0], time.time() - t0

for b in range(1, bmax + 1):
    r, ne, nvars, sec = run(b)
    if r is None: continue
    print(f"k={k} b={b}{' gen' if GEN else ''}{f' h={HB}' if HB is not None else ''}{' flat' if FLAT else ''}: {'SAT' if r else 'UNSAT'}  ({ne} elements, {nvars} vars, {sec:.1f}s)", flush=True)
    if not r: break
