"""Lean files for a cube-and-conquer certificate of the rigid orbit-height theory (log §34.3z¹⁶¹).

Reads OUT_DIR/tree.pkl and OUT_DIR/leaf<i>.pkl written by oh_cert.py and writes
  lean/Mordor/OHCube<H>Terms.lean   the global term table `ohtv<H>c`
  lean/Mordor/OHCube<H>L<k>.lean    leaf theorems (bv_decide), chunked
  lean/Mordor/OHCube<H>.lean        the case tree `ohtree<H>` and `ohAt_<H>c : OHAt H`
  python3 oh_cert_lean.py OUT_DIR LEAN_DIR [chunk=N]
"""
import sys, os, pickle

def main(outdir, leandir, chunk=12):
    T = pickle.load(open(os.path.join(outdir, 'tree.pkl'), 'rb')); H = T['H']; tree = T['tree']
    leaves = []
    def collect(t):
        if t[0] == 'leaf': leaves.append(t)
        elif t[0] == 'bin': collect(t[2]); collect(t[3])
        else:
            for c in t[3]: collect(c)
    collect(tree)
    R = [pickle.load(open(os.path.join(outdir, f'leaf{i}.pkl'), 'rb')) for i in range(len(leaves))]
    # global term table
    gid = {0: 0, 1: 1}; order = [0, 1]
    def g(e):
        if e in gid: return gid[e]
        g(e[0]); g(e[1]); gid[e] = len(order); order.append(e); return gid[e]
    def tterms(tg, terms):
        k = tg[0]
        if k in ('refl', 'bot', 'topr', 'base', 'rankmax'): return [tg[1]]
        if k == 'incr': return [tg[2]]
        if k in ('rank0', 'rank'): return [tg[1], tg[2]]
        if k == 'down': return [tg[2], tg[3]]
        if k == 'trans': return list(tg[1:4])
        if k == 'mono': return [tg[1], tg[2]]
        if k in ('brule', 'arule', 'diag', 'post'): return [tg[2]]
        if k in ('rigA', 'rigB', 'rigD'): return [tg[1]]
        return []
    for (_, lits, _), r in zip(leaves, R):
        for tg in r['tags']:
            for t in tterms(tg, r['terms']): g(r['exprs'][t])
        for a, b, _ in lits: g(a); g(b)
    def expr_lean(e):
        return "⊥" if e == 0 else "⊤" if e == 1 else f"F ({expr_lean(e[0])}) ({expr_lean(e[1])})"
    name = f"{H}c"
    terms_src = f'''import Mordor.OHRigid

/-! Global term table of the cube-and-conquer certificate for `OHAt {H}` (machine-generated by
`experiments/sat/oh_cert_lean.py`; see `OHCube{H}.lean`). -/

namespace Mordor.Ground

/-- The explicit F-terms. -/
def ohtv{name} {{α : Type*}} [Bot α] [Top α] (F : α → α → α) : ℕ → α
''' + "\n".join(f"  | {i} => {expr_lean(e)}" for i, e in enumerate(order)) + "\n  | _ => ⊥\n\nend Mordor.Ground\n"
    open(os.path.join(leandir, f'OHCube{H}Terms.lean'), 'w').write(terms_src)
    def lit_prop(a, b, pos, tv):
        p = f"{tv} {gid[a]} ≤ {tv} {gid[b]}"
        return p if pos else f"¬ {p}"
    # leaf theorems
    files = []
    for c0 in range(0, len(leaves), chunk):
        body = []
        for i in range(c0, min(c0 + chunk, len(leaves))):
            _, lits, _ = leaves[i]; r = R[i]; ex = r['exprs']; tm = r['terms']
            G = lambda t: gid[ex[t]]
            T_ = lambda t: f"(t {G(t)})"
            need = set(); lines = []
            def e(t): need.add(G(t)); return f"e{G(t)}"
            for tg in r['tags']:
                k = tg[0]
                if k == 'refl': lines.append(f"cl_refl {T_(tg[1])}")
                elif k == 'bot': lines.append(f"cl_bot h0 {T_(tg[1])}")
                elif k == 'topr': lines.append(f"cl_top h1 {T_(tg[1])}")
                elif k == 'base': lines.append(f"oh_base O h0 {T_(tg[1])}")
                elif k == 'rankmax': lines.append(f"cl_rankmax hn {T_(tg[1])}")
                elif k == 'incr': lines.append(f"oh_incr O {tg[1]} {tg[1] + 1} rfl {T_(tg[2])}")
                elif k == 'rank0': lines.append(f"cl_rank0 {T_(tg[1])} {T_(tg[2])}")
                elif k == 'rank': lines.append(f"cl_rank {T_(tg[1])} {T_(tg[2])} {tg[3]} {tg[3] + 1} rfl")
                elif k == 'down': lines.append(f"oh_down O {tg[1]} {T_(tg[2])} {T_(tg[3])}")
                elif k == 'trans': lines.append(f"cl_trans {T_(tg[1])} {T_(tg[2])} {T_(tg[3])}")
                elif k == 'mono': lines.append(f"oh_mono O {e(tg[1])} {e(tg[2])}")
                elif k == 'brule': lines.append(f"oh_b O {e(tg[2])} {tg[1]} {tg[1] + 1} rfl")
                elif k == 'arule': lines.append(f"oh_a O {e(tg[2])} {tg[1]} {tg[1] + 1} rfl")
                elif k == 'topbot': lines.append("oh_topbot O h1 h0")
                elif k == 'top': lines.append("oh_top O h1")
                elif k == 'rigA': lines.append(f"oh_rigA R h0 {e(tg[1])}")
                elif k == 'rigB': lines.append(f"oh_rigB R h1 {e(tg[1])}")
                elif k == 'rigD': lines.append(f"oh_rigD R h0 h1 {e(tg[1])}")
                elif k == 'diag': lines.append(f"oh_diag R h1 {e(tg[2])} {tg[1]} {tg[1] + 1} rfl")
                elif k == 'post': lines.append(f"oh_post R h0 h1 {e(tg[2])} {tg[1]}")
                elif k == 'case':
                    a, b, pos = lits[tg[1]]
                    lines.append(f"oh_lit_pos k{tg[1]}" if pos else f"oh_lit_neg k{tg[1]}")
                else: raise ValueError(tg)
            ehyp = "".join(f"\n    (e{j} : t {j} = F (t {gid[order[j][0]]}) (t {gid[order[j][1]]}))" for j in sorted(need))
            khyp = "".join(f"\n    (k{j} : {lit_prop(a, b, pos, 't')})" for j, (a, b, pos) in enumerate(lits))
            haves = "\n".join(f"  have c{q} := {l}" for q, l in enumerate(lines))
            clears = " ".join([f"e{j}" for j in sorted(need)] + [f"k{j}" for j in range(len(lits))])
            body.append(f'''theorem ohleaf{name}_{i} {{α : Type*}} [PartialOrder α] [OrderBot α] [OrderTop α] {{F : α → α → α}}
    {{M : ℕ → Set α}} (R : OHCxR F M {H}) (hn : NoChain α {H + 1}) (t : ℕ → α) (h0 : t 0 = ⊥) (h1 : t 1 = ⊤){ehyp}{khyp} :
    False := by
  have O := R.toOHCx
{haves}
  clear {clears} h0 h1 hn O R
  bv_decide
''')
        k = c0 // chunk; files.append((f'OHCube{H}L{k}', [i for i in range(c0, min(c0 + chunk, len(leaves)))]))
        open(os.path.join(leandir, f'OHCube{H}L{k}.lean'), 'w').write(f'''import Mordor.GroundOH

/-! Leaf certificates {c0}–{min(c0 + chunk, len(leaves)) - 1} of the cube-and-conquer proof of `OHAt {H}`
(machine-generated by `experiments/sat/oh_cert_lean.py`; `bv_decide`, adding `Lean.ofReduceBool` and
`Lean.trustCompiler`). Do not edit by hand. -/

namespace Mordor.Ground
set_option maxHeartbeats 0
set_option maxRecDepth 100000
set_option linter.unusedVariables false

''' + "\n".join(body) + "\nend Mordor.Ground\n")
    # the case tree
    tv = f"(ohtv{name} F)"
    cnt = [0]; lidx = {id(l): i for i, l in enumerate(leaves)}
    def call(leaf, env, ind):
        i = lidx[id(leaf)]; _, lits, _ = leaf; r = R[i]
        need = sorted({gid[r['exprs'][x]] for tg in r['tags'] for x in ([tg[1], tg[2]] if tg[0] == 'mono' else
                       [tg[2]] if tg[0] in ('brule', 'arule', 'diag', 'post') else [tg[1]] if tg[0] in ('rigA', 'rigB', 'rigD') else [])})
        args = " ".join(["rfl"] * len(need)) + " " + " ".join(env[(a, b, pos)] for (a, b, pos) in lits)
        return f"{ind}exact ohleaf{name}_{i} R hn {tv} rfl rfl {args}"
    def neg(l): return (l[0], l[1], not l[2])
    def emit(t, env, ind):
        if t[0] == 'leaf': return [call(t, env, ind)]
        cnt[0] += 1; h = f"q{cnt[0]}"
        if t[0] == 'bin':
            A = t[1]; P = lit_prop(A[0], A[1], True, tv)
            return ([f"{ind}by_cases {h} : {P}", f"{ind}· "] + emit(t[2], {**env, A: h}, ind + "  ") +
                    [f"{ind}· "] + emit(t[3], {**env, neg(A): h}, ind + "  "))
        A, B = t[1], t[2]; cnt[0] += 1; h2 = f"q{cnt[0]}"
        PA = lit_prop(A[0], A[1], True, tv); PB = lit_prop(B[0], B[1], True, tv)
        return ([f"{ind}by_cases {h} : {PA}", f"{ind}· "] + emit(t[3][0], {**env, A: h}, ind + "  ") +
                [f"{ind}· by_cases {h2} : {PB}", f"{ind}  · "] + emit(t[3][1], {**env, B: h2, neg(A): h}, ind + "    ") +
                [f"{ind}  · "] + emit(t[3][2], {**env, neg(A): h, neg(B): h2}, ind + "    "))
    lines = emit(tree, {}, "  ")
    # join "· " markers with the following line
    out = []
    for l in lines:
        if out and out[-1].rstrip().endswith("·"): out[-1] = out[-1].rstrip() + " " + l.lstrip()
        else: out.append(l)
    imports = "\n".join(f"import Mordor.{f}" for f, _ in files)
    ih = "ohAt_lt_five" if H == 5 else "(fun H' h => ohAt_of_riseAt fun H'' hH'' => riseAt_le_three (by omega))"
    src = f'''import Mordor.OHCube{H}Terms
{imports}

/-!
# The orbit-height property at edge-height ≤ {H} by cube-and-conquer (machine-generated by `oh_cert_lean.py`)

The rigid orbit-height theory (`OHCxR`, `OHRigid.top_mem_or_ohCxR`) is refuted by a case tree of {len(leaves)} leaves:
the boundary-orbit case (first `n` with `⊤ ≤ u_n`, first `m` with `d_m ≤ ⊥`) and, inside the hard cases, 3-way splits
on order atoms of boundary-derived terms (`experiments/sat/oh_cube.py`). Each leaf is a drat-trim-verified core checked
by `bv_decide` (`OHCube{H}L*.lean`), so the proof uses `Lean.ofReduceBool` and `Lean.trustCompiler`.
-/

namespace Mordor.Ground
set_option maxHeartbeats 0
set_option maxRecDepth 100000
set_option linter.unusedVariables false

theorem ohtree{name} {{α : Type*}} [PartialOrder α] [OrderBot α] [OrderTop α] {{F : α → α → α}} {{M : ℕ → Set α}}
    (R : OHCxR F M {H}) (hn : NoChain α {H + 1}) : False := by
''' + "\n".join(out) + f'''

end Mordor.Ground

namespace Mordor.OrbitHeight
open Mordor Mordor.Ground

universe u

/-- **The orbit-height property at edge-height ≤ {H}** (cube-and-conquer certificate `ohtree{name}`). -/
theorem ohAt_{name} : OHAt.{{u}} {H} := by
  intro β _ G hn
  rcases top_mem_or_ohCxR {ih} hn G with h | R
  · exact h
  · exact (ohtree{name} R hn).elim

end Mordor.OrbitHeight
'''
    open(os.path.join(leandir, f'OHCube{H}.lean'), 'w').write(src)
    print(f"wrote {len(leaves)} leaves in {len(files)} files, {len(order)} global terms")
    return files

if __name__ == '__main__':
    ch = next((int(a[6:]) for a in sys.argv if a.startswith('chunk=')), 12)
    main(sys.argv[1], sys.argv[2], ch)
