"""Turn a drat-trim core of oh_ground.py into a Lean proof (lean/Mordor/OHHeight<H>.lean) (log §34.3z¹⁵⁹).

Each core clause is mapped back to its provenance tag and emitted as an instance of a lemma of
lean/Mordor/GroundOH.lean or GroundCut.lean; `bv_decide` refutes the conjunction (CaDiCaL + LRAT, kernel-checked).
  python3 oh_lean.py PREFIX core.cnf out.lean      (PREFIX.pkl from `oh_ground.py H … dump PREFIX`)
"""
import sys, pickle

def main(pre, core_path, out_path):
    P = pickle.load(open(pre + '.pkl', 'rb')); H = P['H']; terms = P['terms']
    tagof = {}
    for c, tg in zip(P['clauses'], P['tags']): tagof.setdefault(tuple(sorted(c)), tg)
    core = [tuple(sorted(map(int, l.split()[:-1]))) for l in open(core_path) if l.strip() and not l.startswith(('p', 'c'))]
    tags = [tagof[c] for c in core]
    used = {0, 1}
    for tg in tags:
        for a in tg[1:]:
            pass
    def tterms(tg):
        k = tg[0]
        if k in ('refl', 'bot', 'topr', 'base', 'rankmax'): return [tg[1]]
        if k == 'incr': return [tg[2]]
        if k in ('rank0',): return [tg[1], tg[2]]
        if k == 'rank': return [tg[1], tg[2]]
        if k == 'down': return [tg[2], tg[3]]
        if k == 'trans': return list(tg[1:4])
        if k == 'mono': return [tg[1], tg[2]] + list(terms[tg[1]]) + list(terms[tg[2]])
        if k in ('brule', 'arule'): return [tg[2]] + list(terms[tg[2]])
        return []
    for tg in tags: used |= set(tterms(tg))
    stack = list(used)
    while stack:
        i = stack.pop()
        if terms[i] is not None:
            for j in terms[i]:
                if j not in used: used.add(j); stack.append(j)
    order = sorted(used); ren = {o: k for k, o in enumerate(order)}
    T = lambda i: f"(t {ren[i]})"
    expr = {}
    for o in order:
        expr[o] = "⊥" if o == 0 else "⊤" if o == 1 else f"F ({expr[terms[o][0]]}) ({expr[terms[o][1]]})"
    need_e = set(); lines = []
    def e(i): need_e.add(i); return f"e{ren[i]}"
    for tg in tags:
        k = tg[0]
        if k == 'refl': lines.append(f"cl_refl {T(tg[1])}")
        elif k == 'bot': lines.append(f"cl_bot h0 {T(tg[1])}")
        elif k == 'topr': lines.append(f"cl_top h1 {T(tg[1])}")
        elif k == 'base': lines.append(f"oh_base O h0 {T(tg[1])}")
        elif k == 'rankmax': lines.append(f"cl_rankmax hn {T(tg[1])}")
        elif k == 'incr': lines.append(f"oh_incr O {tg[1]} {tg[1] + 1} rfl {T(tg[2])}")
        elif k == 'rank0': lines.append(f"cl_rank0 {T(tg[1])} {T(tg[2])}")
        elif k == 'rank': lines.append(f"cl_rank {T(tg[1])} {T(tg[2])} {tg[3]} {tg[3] + 1} rfl")
        elif k == 'down': lines.append(f"oh_down O {tg[1]} {T(tg[2])} {T(tg[3])}")
        elif k == 'trans': lines.append(f"cl_trans {T(tg[1])} {T(tg[2])} {T(tg[3])}")
        elif k == 'mono': lines.append(f"oh_mono O {e(tg[1])} {e(tg[2])}")
        elif k == 'brule': lines.append(f"oh_b O {e(tg[2])} {tg[1]} {tg[1] + 1} rfl")
        elif k == 'arule': lines.append(f"oh_a O {e(tg[2])} {tg[1]} {tg[1] + 1} rfl")
        elif k == 'topbot': lines.append("oh_topbot O h1 h0")
        elif k == 'top': lines.append("oh_top O h1")
        else: raise ValueError(tg)
    N = len(order)
    hyps = "\n".join(f"    (e{ren[i]} : t {ren[i]} = F (t {ren[terms[i][0]]}) (t {ren[terms[i][1]]}))" for i in sorted(need_e))
    haves = "\n".join(f"  have c{k} := {l}" for k, l in enumerate(lines))
    tv = "\n".join(f"  | {ren[o]} => {expr[o]}" for o in order)
    es = " ".join("rfl" for _ in sorted(need_e))
    clears = " ".join(f"e{ren[i]}" for i in sorted(need_e))
    src = f'''import Mordor.GroundOH
import Mordor.HeightInduction

/-!
# The orbit-height property at edge-height ≤ {H} (machine-generated by `experiments/sat/oh_lean.py`)

`ohcore{H}` refutes the {len(lines)} ground clauses of a drat-trim-verified unsat core of the orbit-height theory
`OH_{H}` over {N} F-terms built from `⊥, ⊤` (`experiments/sat/oh_ground.py`); every clause is an instance of a lemma
of `GroundOH.lean` / `GroundCut.lean`, and `bv_decide` checks the propositional refutation (LRAT, kernel-checked;
this adds the trusted `Lean.ofReduceBool` / `Lean.trustCompiler` axioms of `bv_decide`).
`ohAt_{H}'`: for every complete lattice of edge-height ≤ {H} and every monotone `G`, `⊤ ∈ R_{H}` — the orbit `M k := R_k`
satisfies `OHCx` except for `⊤ ∉ M {H}`. Do not edit by hand; regenerate.
-/

namespace Mordor.Ground
set_option maxHeartbeats 0
set_option maxRecDepth 100000

theorem ohcore{H} {{α : Type*}} [PartialOrder α] [OrderBot α] [OrderTop α] {{F : α → α → α}} {{M : ℕ → Set α}}
    (O : OHCx F M {H}) (hn : NoChain α {H + 1}) (t : ℕ → α) (h0 : t 0 = ⊥) (h1 : t 1 = ⊤)
{hyps} : False := by
{haves}
  clear {clears} h0 h1 hn O
  bv_decide

/-- The explicit F-terms. -/
def ohtv{H} {{α : Type*}} [Bot α] [Top α] (F : α → α → α) : ℕ → α
{tv}
  | _ => ⊥

end Mordor.Ground

namespace Mordor.OrbitHeight
open Mordor Mordor.Ground

universe u

/-- **The orbit-height property at edge-height ≤ {H}** (via the `bv_decide` certificate `ohcore{H}`). -/
theorem ohAt_{H}' : OHAt.{{u}} {H} := by
  intro β _ G hn
  by_contra hnot
  have O : OHCx (fun x y => G x y) (fun k => Rk G k) {H} :=
    ⟨fun x x' y y' hx hy => (G.mono hx y).trans ((G x').mono hy),
     fun t h => (show t ∈ Set.Iic (⊥ : β) from h),
     fun k t h => Rk_mono (Nat.le_succ k) h,
     fun k s t hst h => Rk_down k hst h,
     fun k x y hx h => mem_succ_of_cell hx le_rfl (Or.inl h),
     fun k x y hx h => mem_succ_of_cell hx le_rfl (Or.inr h),
     hnot⟩
  exact ohcore{H} O hn (ohtv{H} (fun x y => G x y)) rfl rfl {es}

end Mordor.OrbitHeight
'''
    open(out_path, 'w').write(src)
    print(f"wrote {out_path}: {len(lines)} clauses, {N} terms, {len(need_e)} F-equations")

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3])
